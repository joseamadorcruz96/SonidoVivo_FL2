CREATE TABLE ventas.boletas (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                numero_orden VARCHAR(255) UNIQUE,
                                codigo_orden VARCHAR(255) UNIQUE,
                                fecha TIMESTAMP NOT NULL,
                                usuario_id BIGINT,
                                cliente_nombre VARCHAR(255) NOT NULL,
                                cliente_apellidos VARCHAR(255) NOT NULL,
                                cliente_email VARCHAR(255) NOT NULL,
                                calle VARCHAR(255) NOT NULL,
                                departamento VARCHAR(255),
                                region VARCHAR(255) NOT NULL,
                                comuna VARCHAR(255) NOT NULL,
                                indicaciones VARCHAR(255),
                                total INTEGER NOT NULL CHECK (total >= 0),
                                estado VARCHAR(255) NOT NULL
);

CREATE TABLE ventas.detalle_boletas (
                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        boleta_id BIGINT NOT NULL REFERENCES ventas.boletas(id),
                                        producto_codigo VARCHAR(255) NOT NULL,
                                        producto_nombre VARCHAR(255) NOT NULL,
                                        precio_unitario INTEGER NOT NULL CHECK (precio_unitario >= 0),
                                        cantidad INTEGER NOT NULL CHECK (cantidad >= 1),
                                        imagen VARCHAR(255)
);